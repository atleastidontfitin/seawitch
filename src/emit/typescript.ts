import path from 'node:path';
import type { Diagnostic } from '../diagnostics.js';
import type { Expr, Graph, GraphNode, MappedSpan } from '../ir.js';
import { rewriteSpecifier } from '../resolve/imports.js';

// Duplicated tails and this cap are prototype limitations, not language rules.
const EXPANSION_LIMIT = 2000;

export type EmittedFile = {
  sourcePath: string;
  outputPath: string;
  contents: string;
  spans: MappedSpan[];
  graph: Graph;
};

export function emitGraph(
  graph: Graph,
  outputPath: string,
  srcRoot: string,
  outRoot: string,
  referenced: Set<string>,
): { file: EmittedFile } | { diagnostic: Diagnostic } {
  const printer = new Printer();
  printer.write(`// Generated by Seawitch from ${path.basename(graph.filePath)}. Do not edit.\n\n`);
  for (const imported of graph.imports) {
    const specifier = rewriteSpecifier({
      sourceFile: graph.filePath,
      outputFile: outputPath,
      specifier: imported.specifier,
      srcRoot,
      outRoot,
    });
    const names = imported.names.join(', ');
    const keyword = imported.kind === 'type' ? 'import type' : 'import';
    printer.write(`${keyword} { ${names} } from '${specifier}';\n`);
  }
  if (graph.imports.length > 0) {
    printer.write('\n');
  }
  const parameters = graph.signature.params.map((parameter) => `${parameter.name}: ${parameter.typeText}`).join(', ');
  const signatureStart = printer.length;
  printer.write(
    `export function ${graph.signature.name}(${parameters}): ${graph.signature.returnType} {\n`,
  );
  printer.spans.push({
    role: 'signature',
    start: signatureStart,
    end: printer.length,
    line: graph.signature.loc.line,
  });

  const nodes = new Map<string, GraphNode>(graph.nodes.map((node) => [node.id, node]));
  const startEdge = graph.edges.find((edge) => edge.from === 'start');
  if (!startEdge) {
    return {
      diagnostic: {
        code: 'SW101',
        file: graph.displayFile,
        line: 1,
        nodeId: 'start',
        message: 'The entry node must have exactly one unlabeled outgoing edge.',
      },
    };
  }
  const emitted = emitNode(startEdge.to, 2, printer, graph, nodes, referenced);
  if (emitted) {
    return { diagnostic: emitted };
  }
  printer.write('}\n');
  return {
    file: {
      sourcePath: graph.filePath,
      outputPath,
      contents: printer.text(),
      spans: printer.spans,
      graph,
    },
  };
}

function emitNode(
  id: string,
  indent: number,
  printer: Printer,
  graph: Graph,
  nodes: Map<string, GraphNode>,
  referenced: Set<string>,
): Diagnostic | undefined {
  printer.expansions += 1;
  if (printer.expansions > EXPANSION_LIMIT) {
    return {
      code: 'SW103',
      file: graph.displayFile,
      line: nodes.get(id)?.loc.line ?? 1,
      nodeId: id,
      message:
        'Prototype expansion guard stopped emission after 2000 nodes. This is a prototype limitation, not a language rule.',
    };
  }
  const node = nodes.get(id);
  if (!node) {
    return {
      code: 'SW101',
      file: graph.displayFile,
      line: 1,
      message: `Missing node '${id}'.`,
    };
  }
  if (node.kind === 'return') {
    const expression = printExpr(node.value);
    const statement = `return ${expression}`;
    const prefix = ' '.repeat(indent);
    const start = printer.length + prefix.length;
    printer.write(`${prefix}${statement};\n`);
    printer.spans.push({
      role: 'return',
      start,
      end: start + statement.length,
      line: node.loc.line,
      nodeId: node.id,
    });
    return undefined;
  }
  if (node.kind === 'call') {
    const call = printCall(node.callee, node.args);
    recordCall(printer, indent, node, call, referenced.has(node.id), 'call');
    const next = graph.edges.find((edge) => edge.from === node.id);
    return next ? emitNode(next.to, indent, printer, graph, nodes, referenced) : undefined;
  }
  if (node.kind !== 'decision') {
    return {
      code: 'SW101',
      file: graph.displayFile,
      line: node.loc.line,
      nodeId: node.id,
      message: `Cannot emit node '${node.id}'.`,
    };
  }
  const call = printCall(node.callee, node.args);
  const condition = referenced.has(node.id) ? node.id : call;
  if (referenced.has(node.id)) {
    recordCall(printer, indent, node, call, true, 'decision');
  }
  const trueEdge = graph.edges.find((edge) => edge.from === node.id && edge.label === 'true');
  const falseEdge = graph.edges.find((edge) => edge.from === node.id && edge.label === 'false');
  if (!trueEdge || !falseEdge) {
    return {
      code: 'SW104',
      file: graph.displayFile,
      line: node.loc.line,
      nodeId: node.id,
      message: "A decision must have a 'true' edge and a 'false' edge.",
    };
  }
  const conditionPrefix = `${' '.repeat(indent)}if (`;
  const conditionStart = printer.length + conditionPrefix.length;
  printer.write(`${conditionPrefix}${condition}) {\n`);
  if (!referenced.has(node.id)) {
    printer.spans.push({
      role: 'decision',
      start: conditionStart,
      end: conditionStart + call.length,
      line: node.loc.line,
      nodeId: node.id,
    });
  }
  const trueError = emitNode(trueEdge.to, indent + 2, printer, graph, nodes, referenced);
  if (trueError) {
    return trueError;
  }
  printer.write(`${' '.repeat(indent)}} else {\n`);
  const falseError = emitNode(falseEdge.to, indent + 2, printer, graph, nodes, referenced);
  if (falseError) {
    return falseError;
  }
  printer.write(`${' '.repeat(indent)}}\n`);
  return undefined;
}

function recordCall(
  printer: Printer,
  indent: number,
  node: GraphNode,
  call: string,
  bind: boolean,
  role: 'call' | 'decision',
): void {
  if (bind) {
    const prefix = `${' '.repeat(indent)}const ${node.id} = `;
    const start = printer.length + prefix.length;
    printer.write(`${prefix}${call};\n`);
    printer.spans.push({
      role,
      start,
      end: start + call.length,
      line: node.loc.line,
      nodeId: node.id,
    });
    return;
  }
  const prefix = `${' '.repeat(indent)}`;
  const start = printer.length + prefix.length;
  printer.write(`${prefix}${call};\n`);
  printer.spans.push({
    role,
    start,
    end: start + call.length,
    line: node.loc.line,
    nodeId: node.id,
  });
}

function printCall(callee: string, args: Expr[]): string {
  return `${callee}(${args.map(printExpr).join(', ')})`;
}

function printExpr(expression: Expr): string {
  if (expression.kind === 'ref') {
    return expression.name;
  }
  const literal = expression.literal;
  if (literal.kind === 'string') {
    return `'${literal.value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
  }
  if (literal.kind === 'number') {
    return literal.raw;
  }
  if (literal.kind === 'boolean') {
    return literal.value ? 'true' : 'false';
  }
  return 'null';
}

class Printer {
  private chunks: string[] = [];
  length = 0;
  expansions = 0;
  spans: MappedSpan[] = [];

  write(text: string): void {
    this.chunks.push(text);
    this.length += text.length;
  }

  text(): string {
    return this.chunks.join('');
  }
}
