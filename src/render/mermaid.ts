import { formatLabel } from './plaintext.js';

const GENERATED = '    %% Generated by Seawitch. Do not edit.';

export function escapeMermaidLabel(label: string): string {
  return label.replaceAll('#', '#35;').replaceAll('"', '#quot;').replaceAll('<', '#lt;').replaceAll('>', '#gt;');
}

export function renderReaderSource(
  source: string,
  vocabulary: ReadonlyMap<string, string>,
  booleanCallees: ReadonlySet<string> = new Set(),
): string {
  const lines = source.replace(/^\uFEFF/, '').split(/\r?\n/);
  const output: string[] = [];
  for (const line of lines) {
    const body = line.trim();
    if (/^flowchart\s+(?:TD|TB|LR|RL|BT)\s*;?\s*$/.test(body) && output.length === 0) {
      output.push(line.trimEnd());
      output.push(GENERATED);
      continue;
    }
    if (/^\s*%%\s*seawitch\s*:/.test(line)) {
      continue;
    }
    output.push(rewriteLabels(line, vocabulary, booleanCallees));
  }
  while (output.length > 0 && output[output.length - 1] === '') {
    output.pop();
  }
  return `${output.join('\n')}\n`;
}

function rewriteLabels(line: string, vocabulary: ReadonlyMap<string, string>, booleanCallees: ReadonlySet<string>): string {
  let output = '';
  let index = 0;
  while (index < line.length) {
    const open = line.startsWith('["', index) ? '["' : line.startsWith('{"', index) ? '{"' : undefined;
    if (!open) {
      output += line[index];
      index += 1;
      continue;
    }
    const close = open === '["' ? '"]' : '"}';
    const end = line.indexOf(close, index + open.length);
    if (end < 0) {
      output += line.slice(index);
      break;
    }
    const label = line.slice(index + open.length, end);
    output += `${open}${escapeMermaidLabel(formatLabel(label, vocabulary, { decision: open === '{"', booleanCallees }))}${close}`;
    index = end + close.length;
  }
  return output;
}
